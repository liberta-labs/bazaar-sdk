#!/usr/bin/env node
// Compile contracts/KeeperProbe.sol and write the artifact the SDK loads.
//
//     node scripts/build-probe.mjs [path-to-solc]
//
// Needs solc 0.8.34 (the pragma is exact). Without an argument the script uses `solc` from PATH, and on
// Windows falls back to the copy Foundry keeps in WSL (~/.svm/0.8.34/solc-0.8.34). The output,
// packages/sdk/src/probe/artifact.ts, is committed, so users of the package never compile.

import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = join(ROOT, "contracts", "KeeperProbe.sol");
const OUT = join(ROOT, "packages", "sdk", "src", "probe", "artifact.ts");
// The probe runs only inside eth_call, but on whatever chain the keeper points at, so it targets an EVM
// version every Arbitrum chain and Anvil accept.
const ARGS = ["--optimize", "--evm-version", "paris", "--combined-json", "abi,bin-runtime"];

function run(cmd, args) {
  return JSON.parse(execFileSync(cmd, args, { encoding: "utf8", maxBuffer: 64 << 20 }));
}

function onPath(cmd) {
  try {
    execFileSync(cmd, ["--version"], { stdio: "ignore" });
    return true;
  } catch {
    return false;
  }
}

function compile() {
  if (process.argv[2]) return run(process.argv[2], [...ARGS, SOURCE]);
  if (onPath("solc")) return run("solc", [...ARGS, SOURCE]);
  if (process.platform === "win32") {
    const [drive, rest] = SOURCE.split(":");
    const wslSource = `/mnt/${drive.toLowerCase()}${rest.replaceAll("\\", "/")}`;
    // Single-quote for bash, escaping any quote in the path itself.
    const quoted = `'${wslSource.replaceAll("'", `'\\''`)}'`;
    const inner = ["~/.svm/0.8.34/solc-0.8.34", ...ARGS, quoted].join(" ");
    return run("wsl.exe", ["bash", "-lc", inner]);
  }
  return run(join(process.env.HOME ?? "~", ".svm", "0.8.34", "solc-0.8.34"), [...ARGS, SOURCE]);
}

const result = compile();
const key = Object.keys(result.contracts).find((k) => k.endsWith(":KeeperProbe"));
if (!key) throw new Error("solc output has no KeeperProbe");
const contract = result.contracts[key];
const abi = Array.isArray(contract.abi) ? contract.abi : JSON.parse(contract.abi);
const runtime = "0x" + contract["bin-runtime"];
mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(
  OUT,
  "// Generated by scripts/build-probe.mjs from contracts/KeeperProbe.sol (solc 0.8.34, --optimize,\n" +
    "// --evm-version paris). Do not edit.\n" +
    `export const keeperProbeAbi = ${JSON.stringify(abi, null, 2)} as const;\n\n` +
    `export const KEEPER_PROBE_RUNTIME = ${JSON.stringify(runtime)} as const;\n`,
);
console.log(`wrote ${OUT.slice(ROOT.length + 1)} (${(runtime.length - 2) / 2} bytes of runtime code)`);
