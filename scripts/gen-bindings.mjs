#!/usr/bin/env node
// List every exported client function whose first parameter is `ctx: BazaarContext`, per module, so the
// `Bazaar` facade can bind the context for them (bz.trade.createOrder(...) = trade.createOrder(ctx, ...)).
//
//     node scripts/gen-bindings.mjs          write packages/sdk/src/client/bindings.generated.ts
//     node scripts/gen-bindings.mjs --check  exit 1 if the file is out of date (the unit tests run this)

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CLIENT = join(ROOT, "packages", "sdk", "src", "client");
const OUT = join(CLIENT, "bindings.generated.ts");

// The facade's namespaces and the module each binds. Order is the order they appear on Bazaar.
export const MODULES = [
  "markets", "account", "live", "prices", "orders", "trade", "insurance", "signing", "permits",
  "allowance", "relay", "batching", "history", "previews", "termination", "listings", "governance", "uma",
];

export function ctxFunctions(file) {
  const src = ts.createSourceFile(file, readFileSync(file, "utf8"), ts.ScriptTarget.ES2022, true);
  const out = [];
  for (const st of src.statements) {
    if (!ts.isFunctionDeclaration(st) || !st.name) continue;
    const exported = st.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword);
    if (!exported) continue;
    if (ts.getJSDocTags(st).some((t) => t.tagName.text === "internal")) continue;
    const first = st.parameters[0];
    if (first?.type && first.type.getText(src) === "BazaarContext") out.push(st.name.text);
  }
  return [...new Set(out)].sort();
}

export function render() {
  const lines = [
    "// Generated by scripts/gen-bindings.mjs: the context-first functions of each client module. Do not edit.",
    "export const CTX_FUNCTIONS = {",
  ];
  for (const m of MODULES) {
    const names = ctxFunctions(join(CLIENT, `${m}.ts`));
    lines.push(`  ${m}: [${names.map((n) => JSON.stringify(n)).join(", ")}],`);
  }
  lines.push("} as const;", "");
  return lines.join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const text = render();
  if (process.argv.includes("--check")) {
    const cur = (() => {
      try {
        return readFileSync(OUT, "utf8");
      } catch {
        return "";
      }
    })();
    if (cur.replace(/\r\n/g, "\n") !== text) {
      console.error("packages/sdk/src/client/bindings.generated.ts is out of date: run `npm run gen-bindings`");
      process.exit(1);
    }
  } else {
    writeFileSync(OUT, text);
    console.log(`wrote ${OUT.slice(ROOT.length + 1)}`);
  }
}
