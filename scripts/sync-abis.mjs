#!/usr/bin/env node
// Copy the contract ABIs from a Bazaar checkout into the SDK as typed modules, and report what changed.
//
//     node scripts/sync-abis.mjs ../bazaar
//
// The ABIs are the MIT-licensed files `make abis` writes to the Bazaar repository's abi/ directory.
// Each is written to packages/sdk/src/abi/<Name>.ts as an `as const` array, so viem infers every
// function's argument and return types. The Bazaar commit they came from is recorded in source.ts.
// After a contract change that alters an ABI, run this, then `npm run build && npm test`.

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const NAMES = ["BazaarFactory", "BazaarOracle", "BazaarPair", "BazaarPairLens", "BazaarPairTerminator"];
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const DEST = join(ROOT, "packages", "sdk", "src", "abi");

const camel = (name) => name[0].toLowerCase() + name.slice(1) + "Abi";

function canon(p) {
  if (p.type.startsWith("tuple")) return "(" + p.components.map(canon).join(",") + ")" + p.type.slice(5);
  return p.type;
}

function signatures(abi) {
  const out = new Set();
  for (const e of abi) {
    if (e.type === "function" || e.type === "event" || e.type === "error") {
      out.add(`${e.type} ${e.name}(${(e.inputs ?? []).map(canon).join(",")})`);
    }
  }
  return out;
}

function previous(name) {
  const file = join(DEST, `${name}.ts`);
  if (!existsSync(file)) return [];
  const text = readFileSync(file, "utf8");
  const start = text.indexOf("[");
  const end = text.lastIndexOf("] as const");
  return start >= 0 && end > start ? JSON.parse(text.slice(start, end + 1)) : [];
}

// An untrusted checkout must not run code through git: no fsmonitor hook, no hooks path.
const SAFE_GIT = ["-c", "core.fsmonitor=false", "-c", "core.hooksPath=/dev/null"];

function sourceCommit(dir) {
  try {
    const out = execFileSync("git", [...SAFE_GIT, "-C", dir, "log", "-1", "--format=%H %cs", "--", "abi"], { encoding: "utf8" }).trim();
    const [commit, date] = out.split(" ");
    const dirty = execFileSync("git", [...SAFE_GIT, "-C", dir, "status", "--porcelain", "--", "abi"], { encoding: "utf8" }).trim();
    return { commit: commit ?? "", date: date ?? "", dirty: dirty.length > 0 };
  } catch {
    return { commit: "", date: "", dirty: false };
  }
}

function main() {
  const arg = process.argv[2];
  if (!arg) {
    console.log("usage: node scripts/sync-abis.mjs <bazaar checkout>");
    return 2;
  }
  const checkout = resolve(arg);
  const src = existsSync(join(checkout, "abi")) ? join(checkout, "abi") : checkout;
  if (!existsSync(join(src, "BazaarPair.json"))) {
    console.log(`no Bazaar ABIs under ${src}`);
    return 1;
  }
  mkdirSync(DEST, { recursive: true });
  let changed = 0;
  for (const name of NAMES) {
    const fresh = JSON.parse(readFileSync(join(src, `${name}.json`), "utf8"));
    const old = previous(name);
    const a = signatures(fresh);
    const b = signatures(old);
    const added = [...a].filter((s) => !b.has(s)).sort();
    const removed = [...b].filter((s) => !a.has(s)).sort();
    if (added.length || removed.length) {
      changed++;
      console.log(`${name}:`);
      for (const s of added) console.log(`  + ${s}`);
      for (const s of removed) console.log(`  - ${s}`);
    }
    const body =
      `// Generated by scripts/sync-abis.mjs from the Bazaar repository's abi/${name}.json (MIT). Do not edit.\n` +
      `export const ${camel(name)} = ${JSON.stringify(fresh, null, 2)} as const;\n`;
    writeFileSync(join(DEST, `${name}.ts`), body);
  }
  const s = sourceCommit(checkout);
  writeFileSync(
    join(DEST, "source.ts"),
    "// Generated by scripts/sync-abis.mjs: the Bazaar commit the ABIs were copied from.\n" +
      `export const ABI_SOURCE = ${JSON.stringify(s)} as const;\n`,
  );
  console.log(changed ? `${changed} ABI(s) changed; run the build and the tests` : "ABIs unchanged");
  if (s.commit) console.log(`source: Bazaar ${s.commit.slice(0, 10)} (${s.date})${s.dirty ? ", with uncommitted ABI changes" : ""}`);
  return 0;
}

process.exit(main());
